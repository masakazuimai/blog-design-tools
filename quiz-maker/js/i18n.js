// 文言を取り出し {name} を差し込む
export function t(key, params = {}) {
  const value = DICT[LANG][key] ?? DICT.ja[key] ?? key;
  if (typeof value !== 'string') return value;
  return value.replace(/\{(\w+)\}/g, (_, name) => (params[name] ?? `{${name}}`));
}
